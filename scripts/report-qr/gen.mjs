#!/usr/bin/env node
// Writes the vet report v2 QR (CUL-2291, row VR2-11; v2 spec §5.10) to
// supabase/functions/generate-report/reportQrV2.generated.ts: the URL and its module matrix,
// generated together so they can never disagree. The Edge Function carries no QR encoder.
//
// REPOINTING. The QR points at the consumer landing (https://getculprit.app) until the vets page
// (getculprit.app/vets, CUL-282) is live; the repoint follows that page and is one command:
//   NODE_PATH=<dir with qrcode@1.5.4> node scripts/report-qr/gen.mjs https://getculprit.app/vets
// then commit the regenerated module. reportQrV2.test.ts refuses a URL with a query string or a
// fragment (the QR is tokenless: it identifies nothing), and the print-survival job decodes the
// printed QR off a degraded raster and requires it to read back exactly this URL.
//
// Level Q (about 25% recovery), for a photocopied page.
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const QR = require('qrcode')

const url = process.argv[2] ?? 'https://getculprit.app'
const parsed = new URL(url)
if (parsed.protocol !== 'https:' || parsed.search !== '' || parsed.hash !== '' || url.includes('?') || url.includes('#')) {
  throw new Error(`the report QR is an https URL with no query string or fragment: ${url}`)
}
const q = QR.create(url, { errorCorrectionLevel: 'Q' })
const n = q.modules.size
const rows = []
for (let y = 0; y < n; y++) {
  let r = ''
  for (let x = 0; x < n; x++) r += q.modules.data[y * n + x] ? '1' : '0'
  rows.push(r)
}
const out = [
  '// GENERATED by scripts/report-qr/gen.mjs (CUL-2291, row VR2-11). Do not edit by hand: re-run the script',
  '// with the new URL, so the URL and the matrix move together.',
  `// Source: ${JSON.stringify(url)}, error correction level Q, ${n}×${n} modules.`,
  '',
  `export const REPORT_QR_URL = ${JSON.stringify(url)}`,
  '',
  'export const REPORT_QR_MATRIX: readonly string[] = [',
  ...rows.map((r) => `  '${r}',`),
  ']',
  '',
].join('\n')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const target = path.join(root, 'supabase', 'functions', 'generate-report', 'reportQrV2.generated.ts')
fs.writeFileSync(target, out)
console.log(`wrote ${path.relative(root, target)}: ${url}, ${n}×${n}`)
